def get_text(lang: str, key: str) -> str:
    """Get a translated text for the given language and key."""
    if lang not in TRANSLATIONS:
        lang = DEFAULT_LANGUAGE
    
    translations = TRANSLATIONS.get(lang, TRANSLATIONS[DEFAULT_LANGUAGE])
    return translations.get(key, TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key))


def get_language_name(lang_code: str) -> str:
    """Get the native name of a language."""
    return SUPPORTED_LANGUAGES.get(lang_code, lang_code)


def detect_language_from_text(text: str) -> str:
    """Basic language detection from text content."""
    # Simple character-based detection
    if any('\u0600' <= c <= '\u06FF' for c in text):
        # Arabic script - could be Arabic, Farsi, or Kurdish
        if any('\u06A9' == c or '\u06CC' == c or 'ی' in text or 'ک' in text for c in text):
            # Check for Kurdish/Persian specific characters
            if 'ژ' in text or 'ڤ' in text:
                return 'ku'
            return 'fa'
        return 'ar'
    
    # Check for specific language patterns
    turkish_chars = set('çğıöşüÇĞİÖŞÜ')
    if any(c in turkish_chars for c in text):
        return 'tr'
    
    swedish_chars = set('åäöÅÄÖ')
    if any(c in swedish_chars for c in text):
        return 'sv'
    
    german_chars = set('äöüßÄÖÜ')
    if any(c in german_chars for c in text):
        return 'de'
    
    french_words = ['le', 'la', 'les', 'des', 'un', 'une', 'est', 'sont', 'nous', 'vous']
    text_lower = text.lower()
    if any(word in text_lower.split() for word in french_words):
        return 'fr'
    
    spanish_words = ['el', 'la', 'los', 'las', 'es', 'son', 'nosotros', 'usted']
    if any(word in text_lower.split() for word in spanish_words):
        return 'es'
    
    return 'en'  # Default to English for Latin script
